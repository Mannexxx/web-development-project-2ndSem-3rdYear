CREATE TABLE IF NOT EXISTS seller_applications (
  id                       INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id                  INT UNSIGNED NOT NULL,
  first_name               VARCHAR(80) NOT NULL,
  middle_name              VARCHAR(80) NULL,
  last_name                VARCHAR(80) NOT NULL,
  sex                      ENUM('female','male','other') NOT NULL,
  date_of_birth            DATE NOT NULL,
  house_number             VARCHAR(80) NOT NULL,
  street_village           VARCHAR(120) NOT NULL,
  barangay                 VARCHAR(120) NOT NULL,
  municipality             VARCHAR(120) NOT NULL,
  id_type                  VARCHAR(40) NOT NULL,
  id_front_path            VARCHAR(255) NULL,
  id_back_path             VARCHAR(255) NULL,
  terms_accepted_at        DATETIME NOT NULL,
  privacy_accepted_at      DATETIME NOT NULL,
  guidelines_accepted_at   DATETIME NOT NULL,
  biometric_consent_at     DATETIME NOT NULL,
  agreement_version        VARCHAR(40) NOT NULL,
  status                   ENUM('pending','approved','rejected','changes_requested') NOT NULL DEFAULT 'pending',
  didit_session_id         VARCHAR(80) NULL,
  didit_status             VARCHAR(32) NOT NULL DEFAULT 'Not Started',
  didit_updated_at         DATETIME NULL,
  didit_event_created_at   DATETIME NULL,
  submitted_at             DATETIME NOT NULL,
  reviewed_at              DATETIME NULL,
  decided_by               INT UNSIGNED NULL,
  review_note              VARCHAR(1000) NULL,
  retain_until             DATETIME NULL,
  created_at               DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at               DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_seller_application_user (user_id),
  UNIQUE KEY uq_seller_application_didit_session (didit_session_id),
  KEY idx_seller_application_queue (status, submitted_at),
  KEY idx_seller_application_retention (retain_until),
  CONSTRAINT fk_seller_application_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_seller_application_admin FOREIGN KEY (decided_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS didit_webhook_events (
  event_id     VARCHAR(80) NOT NULL,
  session_id   VARCHAR(80) NOT NULL,
  received_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (event_id),
  KEY idx_didit_webhook_session (session_id, received_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
